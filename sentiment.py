# ---------------------------------------------------------------- 修饰
# 只认「紧贴情感词前面、以它结尾」的否定词与程度副词。
# 用「包含」判断会出事：比如「特别支持」里含「别」，会被误判成否定。
NEGATORS = ("不", "不太", "没", "没有", "没法", "无", "未", "非",
            "不会", "不是", "不能", "不用", "并不")
INTENSIFIERS = {
    "很": 1.4, "太": 1.6, "非常": 1.8, "特别": 1.6, "超级": 1.8, "极": 2.0,
    "巨": 1.6, "贼": 1.5, "真": 1.3, "实在": 1.4, "简直": 1.6, "完全": 1.6,
    "有点": 0.7, "一点": 0.7, "稍微": 0.6, "略": 0.6,
}

# 出现这些词时，整条评论更可能是「在讨论」而不是「在表态」，降低判定强度
WEAK_MARKERS = ("？", "?", "吗", "呢", "吧", "请问", "是不是", "有没有")


def _prefix(text: str, idx: int, span: int = 4) -> str:
    return text[max(0, idx - span):idx]


def score_text(text: str) -> int:
    """返回整数情感分：正数偏正面，负数偏负面，0 为中性。"""
    if not text:
        return 0
    total = 0.0
    for table, sign in ((POSITIVE, 1), (NEGATIVE, -1)):
        for word, weight in table.items():
            start = 0
            while True:
                idx = text.find(word, start)
                if idx == -1:
                    break
                start = idx + len(word)
                w = float(weight) * sign
                head = _prefix(text, idx)
                if any(head.endswith(neg) for neg in NEGATORS):
                    w = -w
                for adv, multi in INTENSIFIERS.items():
                    if head.endswith(adv):
                        w *= multi
                        break
                total += w

    if any(mark in text for mark in WEAK_MARKERS):
        total *= 0.75

    if total >= 1.0:
        return int(round(total))
    if total <= -1.0:
        return int(round(total))
    return 0


def label_of(score: int) -> str:
    if score >= 1:
        return "pos"
    if score <= -1:
        return "neg"
    return "neu"


